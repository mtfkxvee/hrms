import { cleanupOutdatedCaches, precacheAndRoute } from "workbox-precaching"
import { clientsClaim } from "workbox-core"

import { initializeApp } from "firebase/app"
import { getMessaging, onBackgroundMessage } from "firebase/messaging/sw"

// X-Sha mode offline: halaman /hrms diambil dari server (network-first). Jika server down
// (gagal, 5xx, atau tidak menjawab dalam BATAS_HALAMAN_MS), pakai salinan terakhir supaya
// karyawan tetap bisa check-in; datanya diantrekan di HP (src/offline/antrean.js).
// Hanya berlaku jika service worker terdaftar dengan scope /hrms (lihat main.js).
const CACHE_HALAMAN = "xpeople-halaman-v1"
const KUNCI_HALAMAN = "/hrms"
const BATAS_HALAMAN_MS = 6000

function halamanApp(url) {
	return url.origin === self.location.origin && (url.pathname === "/hrms" || url.pathname.startsWith("/hrms/"))
}

function denganBatas(promise, ms) {
	return new Promise((resolve, reject) => {
		const timer = setTimeout(() => reject(new Error("timeout")), ms)
		promise.then(
			(value) => {
				clearTimeout(timer)
				resolve(value)
			},
			(error) => {
				clearTimeout(timer)
				reject(error)
			}
		)
	})
}

async function ambilHalamanApp(request) {
	const cache = await caches.open(CACHE_HALAMAN)
	try {
		const response = await denganBatas(fetch(request), BATAS_HALAMAN_MS)
		if (response.ok && !response.redirected) {
			await cache.put(KUNCI_HALAMAN, response.clone())
			return response
		}
		if (response.status < 500) return response
		return (await cache.match(KUNCI_HALAMAN)) || response
	} catch (error) {
		const salinan = await cache.match(KUNCI_HALAMAN)
		if (salinan) return salinan
		throw error
	}
}

self.addEventListener("fetch", (event) => {
	const request = event.request
	if (request.method !== "GET" || request.mode !== "navigate") return
	if (!halamanApp(new URL(request.url))) return
	event.respondWith(ambilHalamanApp(request))
})

// Use the precache manifest generated by Vite
precacheAndRoute(self.__WB_MANIFEST)

// Clean up old caches
cleanupOutdatedCaches()

const jsonConfig = new URL(location).searchParams.get("config")

// Firebase config initialization
try {
	const firebaseApp = initializeApp(JSON.parse(jsonConfig))
	const messaging = getMessaging(firebaseApp)

	function isChrome() {
		return navigator.userAgent.toLowerCase().includes("chrome")
	}

	onBackgroundMessage(messaging, (payload) => {
		const notificationTitle = payload.data.title
		let notificationOptions = {
			body: payload.data.body || "",
		}
		if (payload.data.notification_icon) {
			notificationOptions["icon"] = payload.data.notification_icon
		}
		if (isChrome()) {
			notificationOptions["data"] = {
				url: payload.data.click_action,
			}
		} else {
			if (payload.data.click_action) {
				notificationOptions["actions"] = [
					{
						action: payload.data.click_action,
						title: "View Details",
					},
				]
			}
		}
		self.registration.showNotification(notificationTitle, notificationOptions)
	})

	if (isChrome()) {
		self.addEventListener("notificationclick", (event) => {
			event.stopImmediatePropagation()
			event.notification.close()
			if (event.notification.data && event.notification.data.url) {
				clients.openWindow(event.notification.data.url)
			}
		})
	}
} catch (error) {
	console.log("Failed to initialize Firebase", error)
}

self.skipWaiting()
clientsClaim()
console.log("Service Worker Initialized")
